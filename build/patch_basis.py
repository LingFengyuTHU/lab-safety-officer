def main() -> int:
    text = TARGET.read_text(encoding="utf-8")
    changed = 0
    missing = []

    for key, basis in BASIS.items():
        # 定位该知识点的 basis 块并整体替换
        pat = re.compile(
            r"(  " + re.escape(key) + r": \{.*?basis: \[)(.*?)(\n    \],)",
            re.S,
        )
        m = pat.search(text)
        if not m:
            missing.append(key)
            continue
        lines = ["\n" + "      '" + s + "'" for s in basis]
        new_body = ",".join(lines)
        text = pat.sub(lambda mm: mm.group(1) + new_body + mm.group(3), text, count=1)
        changed += 1

    if missing:
        print("[error] 未定位到以下知识点的 basis 块:", missing)
        return 1

    TARGET.write_text(text, encoding="utf-8")
    print(f"[ok] 已为 {changed} 条知识点补充可核查的规范依据")
    return 0


if __name__ == "__main__":
    sys.exit(main())
